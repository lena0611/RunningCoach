/**
 * 프롬프트 **맨 끝**에 세우는 이번 턴 사용자 요청 (2026-09-16).
 *
 * #795 가 얻은 교훈은 "읽는 순서상 마지막이 이긴다"였는데, 그 자리를 **실행 수치**에만 줬다.
 * 그 결과 프롬프트의 마지막 블록이 예정 세션 목록이 되고, 정작 **사용자 질문은 84KB JSON 한가운데
 * `userNote` 필드**로 묻혔다 — 프롬프트에서 가장 안 보이는 자리다.
 *
 * 2026-09-16 실사고: 코치가 "다음엔 피로골절 의심 신호를 족저근막염이랑 비교해서 정리해드릴게요"로
 * 맺은 **바로 다음 턴**에 사용자가 "비교하기 쉽게 표로 보여줘"라고 했는데, **두 번 모두** 제안한
 * 통증 구분이 아니라 이번 주 스케줄(9/17 Easy · 9/20 Recovery · 9/22 Easy+Strides …)을 표로 비교했다.
 * 대상이 생략된 짧은 요청에서 가장 눈에 띄는 블록이 곧 예정 세션 목록이었기 때문이다.
 *
 * ⚠ 1차 문구는 "직전 답변에서 **네가 제안한** 그 내용"이었는데, 그것만으로는 부족했다 —
 * 직전 답변이 제안으로 맺지 않은 턴("그거 표로 정리해줘")에서는 가리킬 대상이 **정의되지 않아**
 * 모델이 다시 스케줄로 넓혀 읽었다. 코치에게 직접 물어 확인한 자백: "'그거'는 직전 답변의
 * 족저근막염 vs 근육통을 가리키는 게 맞고, 주간 스케줄 표는 대상 오독입니다." 그래서 ① 제안이
 * 없을 때의 기본값(직전 답변의 주제)과 ② 스케줄을 주제로 삼을 조건을 함께 못박는다.
 *
 * 그래서 실행 지침 꼬리표 **뒤에** 요청을 한 번 더 세운다. 꼬리표의 "이전 숫자는 폐기" 효력은
 * 컨텍스트 JSON 뒤라는 위치에서 나오므로 그대로 유지되고, 여기서는 **무엇에 답할 것인가**만 되세운다.
 *
 * 자동 디브리핑처럼 사용자가 아무 말도 하지 않은 턴은 빈 문자열이라 아무것도 붙지 않는다.
 */
export function buildTurnRequestTail(userNote: unknown): string {
  if (typeof userNote !== 'string') return ''
  const note = userNote.trim()
  if (!note) return ''
  return (
    '\n\n[이번 턴 사용자 요청 — 위 데이터와 지침은 재료일 뿐, 답할 대상은 이것이다]\n' +
    note +
    '\n\n대상이 생략된 요청이면("표로 보여줘", "짧게 정리해줘", "응 해줘", "그거 세 줄로") ' +
    '새 주제를 고르지 말고 **직전 답변이 다루던 바로 그 주제**를 가리킨다 — 직전 답변이 제안으로 ' +
    '맺었으면 그 제안이고, 제안이 없었으면 직전 답변의 내용 그 자체다. ' +
    '위 예정 세션 실행 지침은 실행 수치를 말해야 할 때의 출처일 뿐 이번 턴의 주제가 아니다. ' +
    '**예정 세션·주간 스케줄은 사용자가 스케줄을 직접 물었을 때만 주제가 된다** — ' +
    '직전 답변이 스케줄 얘기가 아니었으면 스케줄 표를 내지 마라.\n\n' +
    // 시스템 지침에 세 번 적고도 계속 샜다("발이 조용한지" → "상태가 조용할 때만" → "통증이 완전히
    // 조용할 때까지"). 이 스레드의 옛 답변이 전부 그 표현을 쓰고 있어서 모델이 **자기 과거 말투**를
    // 따라간 것이다 — #795 와 같은 구조라 같은 해법을 쓴다. 맨 끝에서 다시 세운다.
    '금지 표현(이 스레드의 옛 답변에 있더라도 따라 쓰지 마라): 몸·통증·상태를 "조용하다"로 말하지 ' +
    '않는다 — 조용한/조용할/조용히/조용하게/조용해지면 전부 금지다. "통증이 없는/아프지 않은/괜찮은"으로 ' +
    '바꿔 쓴다. 훈련을 "밀다/밀어붙이다"로 말하지 않는다. 내부 상태값(monitoring·active·resolved)은 ' +
    '관찰 중·관리 중·해소로 옮긴다.'
  )
}
